"""Write COVERAGE.md from the intents, sidecars and measured result rows. Never hand-edit COVERAGE.md.
Usage: python -I generators/write_coverage.py
"""
from pathlib import Path
import json, collections, sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from map.check_links import page_data
from map.build import main as build_map, display, COVERAGE_DISPLAY
R = Path(__file__).resolve().parents[1]
def coverage_display(status):
    return COVERAGE_DISPLAY.get(status, display(status))

ORDER = ['wanted', 'planned', 'partial', 'covered', 'blocked']


def main(output=None, page_path=None):
    intents = [json.loads(p.read_text()) for p in sorted((R / 'intent').glob('*.json')) if not p.name.endswith('.schema.json')]
    if page_path is None:
        build_map()
        page_path = R/'map/index.html'
    page = Path(page_path).read_text()
    data = page_data(page)
    summaries = {}
    for t in data['topics']:
        cells = [c for f in t['features'] for c in f['cells'] if c['applicable'] and c['coverage'] != 'no source']
        states = {c['coverage'] for c in cells}
        status = next((i['status'] for i in intents if i['intent_id']==t['id'] and 'status' in i), 'covered' if states=={'covered'} else 'partial')
        summaries[t['id']] = (status, sorted({m for c in cells for m in c['missing']} | {'native file missing' for c in cells if c['coverage']=='planned'}))
    for i in intents: i['status'] = summaries[i['intent_id']][0]
    counts = collections.Counter(i['status'] for i in intents)
    text = '# Coverage\n\nGenerated by `python -I generators/write_coverage.py`. Intent status describes the topic; cells describe available files and measured runs.\n\n'
    text += '| Status | Count |\n| --- | ---: |\n' + ''.join(f'| {coverage_display(s)} | {counts[s]} |\n' for s in ORDER)
    if (R / 'standard/dxf-inventory.json').exists():
        standard = json.loads((R / 'standard/dxf-inventory.json').read_text())
        standard_counts = collections.Counter(row['dataset']['status'] for row in standard)
        text += '\n## Standard inventory\n\nDataset coverage against the [DXF item inventory](standard/dxf-inventory.json). Counts describe item evidence, not complete conformance.\n\n| Status | Count |\n| --- | ---: |\n'
        text += ''.join(f'| {display(status)} | {standard_counts[status]} |\n' for status in ('included', 'partial', 'present', 'future', 'omitted'))
    cell_counts = collections.Counter(c['coverage'] for t in data['topics'] for f in t['features'] for c in f['cells'])
    text += '\n## Cell status counts\n\n| Status | Count |\n| --- | ---: |\n' + ''.join(f'| {coverage_display(s)} | {cell_counts[s]} |\n' for s in ['covered', 'partial', 'planned', 'wanted', 'blocked', 'no source', 'not applicable'])
    text += '\n| Intent | Title | Status | Features | Missing pieces |\n| --- | --- | --- | ---: | --- |\n'
    for s in ORDER:
        for i in sorted((x for x in intents if x['status'] == s), key=lambda x: (x['intent_id'].startswith('background_'), x['intent_id'])):
            n = len([f for f in i.get('features',[]) if f.lower()!='file identity']) or 1
            text += f"| [{i['intent_id']}](intent/{i['intent_id']}.json) | {i['title']} | {coverage_display(s)} | {n} | {'; '.join(summaries[i['intent_id']][1])} |\n"
    files = collections.Counter(); formats = collections.defaultdict(set)
    for folder in ('native', 'cross'):
        for sc in sorted((R / folder).rglob('*.json')):
            m = json.loads(sc.read_text()); where = sc.relative_to(R).parts[:2]
            key = '/'.join(where[:2]) if folder == 'cross' else 'native/' + where[1]
            files[key] += 1; formats[key].add(f"{m['format']} {m['encoding']}" if m['format'] == 'DXF' else 'DWG')
    text += '\n## Drawings by set\n\nEach drawing has a sidecar. Rows are checker results per expected field.\n\n| Set | Drawings | Formats and encodings | Rows same | Rows differs | Rows absent | Rows not scored | Rows refused |\n| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: |\n'
    rows = collections.defaultdict(collections.Counter)
    seen = set()
    for p in sorted((R / 'results').glob('*checks.json')):
        measured=json.loads(p.read_text())
        if not isinstance(measured,list): continue
        for r in measured:
            observation = tuple(r.get(k) for k in ('file','field','reader','converter'))
            if observation in seen: continue
            seen.add(observation)
            parts = Path(r['file']).parts
            key = '/'.join(parts[:2]) if parts[0] == 'cross' else 'native/' + parts[1]
            rows[key][r['status']] += 1
    for key in sorted(files):
        c = rows[key]
        text += f"| {key} | {files[key]} | {', '.join(sorted(formats[key]))} | {c['same']} | {c['differs']} | {c['absent']} | {c['not_scored']} | {c['refused']} |\n"
    nr = json.loads((R / 'results/cross_not_run.json').read_text()) if (R / 'results/cross_not_run.json').exists() else {}
    if nr:
        text += '\n## Not run: the re-saver cannot write the requested format\n\nCapability gaps, recorded in `results/cross_not_run.json`; they are not failed rows.\n\n| Pair | Outputs not run | Reasons |\n| --- | ---: | --- |\n'
        by = collections.defaultdict(list)
        for k, v in nr.items():
            by[k.split('|')[0]].append(v)
        for pair, reasons in sorted(by.items()):
            text += f"| {pair} | {len(reasons)} | {'; '.join(sorted(set(reasons)))} |\n"
    (Path(output) if output else R / 'COVERAGE.md').write_text(text)
    print('COVERAGE.md written;', dict(counts))


if __name__ == '__main__':
    main()
